fn deep_policy() -> RetrievalPolicy {
    RetrievalPolicy {
        lexical: "trigram3".into(),
        vector: true,
        rerank: true,
        top_k: 5,
    }
}

fn setup() -> Connection {
    let conn = Connection::open_in_memory().unwrap();
    crate::db::schema::migrate(&conn).unwrap();
    conn.execute(
        "INSERT INTO sessions(id,title,created,updated) VALUES('s1','t','2026-01-01T00:00:00Z','2026-01-01T00:00:00Z')",
        [],
    )
    .unwrap();
    let text = SECTIONS
        .iter()
        .map(|(h, b)| format!("## {h}\n{b}"))
        .collect::<Vec<_>>()
        .join("\n");
    let (_id, n) = index_document(&conn, "s1", "whitepaper.pdf", "pdf", &text).unwrap();
    assert_eq!(n, SECTIONS.len(), "每节应切成一块");
    conn
}

/// 基线(P7 之前的检索):纯覆盖率打分,取 Top-3 的 ord。
fn baseline_top3(conn: &Connection, query: &str) -> Vec<i64> {
    let tokens = query_tokens(query);
    coverage_candidates(conn, "s1", &tokens, None)
        .unwrap()
        .into_iter()
        .take(3)
        .map(|c| c.ord)
        .collect()
}

/// 混合检索(deep 档)Top-3 的 ord。
fn hybrid_top3(conn: &Connection, query: &str) -> Vec<i64> {
    search_with_policy(conn, "s1", query, None, 3, &deep_policy())
        .unwrap()
        .hits
        .into_iter()
        .map(|h| h.ord)
        .collect()
}

#[test]
fn hybrid_top3_hit_rate_beats_baseline() {
    let conn = setup();
    let mut base_hit = 0usize;
    let mut new_hit = 0usize;
    for (q, want) in GOLDEN {
        let b = baseline_top3(&conn, q);
        let n = hybrid_top3(&conn, q);
        let b_ok = b.contains(&(*want as i64));
        let n_ok = n.contains(&(*want as i64));
        base_hit += b_ok as usize;
        new_hit += n_ok as usize;
        if b_ok != n_ok {
            eprintln!(
                "[golden] {q} -> want ord {want}: baseline {} {b:?}, hybrid {} {n:?}",
                if b_ok { "HIT" } else { "MISS" },
                if n_ok { "HIT" } else { "MISS" },
            );
        }
    }
    eprintln!(
        "[golden] Top-3 命中率: baseline {base_hit}/{} = {:.0}%, hybrid {new_hit}/{} = {:.0}%",
        GOLDEN.len(),
        base_hit as f64 / GOLDEN.len() as f64 * 100.0,
        GOLDEN.len(),
        new_hit as f64 / GOLDEN.len() as f64 * 100.0,
    );
    assert!(
        new_hit >= base_hit,
        "hybrid({new_hit}) 不得低于 baseline({base_hit})"
    );
}
